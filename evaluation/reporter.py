"""
Todards Pipeline — Evaluation Report Generator

Generates comprehensive Markdown and JSON reports for each pipeline execution,
including stage breakdowns, duplicate counts, moderation logs, and LLM throughput.
"""

import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

from evaluation.metrics import PipelineMetrics
from config.settings import EVALUATION_REPORTS_DIR

logger = logging.getLogger("todards.reporter")


class PipelineReporter:
    """
    Renders structured reports from collected PipelineMetrics.
    """

    def __init__(self, reports_dir: Optional[Path] = None):
        self.reports_dir = Path(reports_dir or EVALUATION_REPORTS_DIR)
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def generate_report(self, metrics: PipelineMetrics) -> Dict[str, Path]:
        """
        Saves both JSON and Markdown reports.
        Returns paths to the generated files.
        """
        data = metrics.to_dict()
        date_str = data["date"]

        json_path = self.reports_dir / f"{date_str}_report.json"
        md_path = self.reports_dir / f"{date_str}_report.md"

        # 1. Write JSON Report
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=4)

        # 2. Render Markdown Report
        md_content = self._render_markdown(data)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        logger.info(f"Evaluation reports generated: {md_path.name} & {json_path.name}")
        return {"json": json_path, "markdown": md_path}

    def _render_markdown(self, data: Dict[str, Any]) -> str:
        vol = data.get("volume", {})
        llm = data.get("llm_performance", {})
        stages = data.get("stages_duration_seconds", {})

        md = []
        md.append(f"# Todards Pipeline Evaluation Report — {data.get('date')}")
        md.append(f"\n> **Execution Timestamp**: {data.get('timestamp')}")
        md.append(f"> **Total Duration**: {data.get('duration_seconds')} seconds\n")

        # Key Highlights
        md.append("## Executive Summary\n")
        md.append("| Metric | Value |")
        md.append("|---|---|")
        md.append(f"| Total Scraped Articles | {vol.get('total_scraped', 0)} |")
        md.append(f"| Guardrail Filtered (NSFW/Rumor) | {vol.get('guardrail_rejected', 0)} |")
        md.append(f"| Semantic Duplicates Removed | {vol.get('dedup_removed', 0)} |")
        md.append(f"| Category Reassignments | {vol.get('category_reassignments', 0)} |")
        md.append(f"| Final Published Articles | {vol.get('final_articles', 0)} ({vol.get('final_categories', 0)} categories) |")
        md.append(f"| Total Ollama LLM Calls | {llm.get('total_calls', 0)} |")
        md.append(f"| Ollama Avg Latency | {llm.get('avg_response_time', 0)}s |")

        # Stage Breakdown Table
        md.append("\n## Stage Timing Breakdown\n")
        md.append("| Pipeline Stage | Duration (s) |")
        md.append("|---|---|")
        for stage, duration in sorted(stages.items()):
            md.append(f"| {stage.replace('_', ' ').title()} | {duration:.2f}s |")

        # Category Scrape Breakdown
        md.append("\n## Ingestion Breakdown\n")
        md.append("| Category | Articles Scraped |")
        md.append("|---|---|")
        for cat, cnt in vol.get("scraped_by_category", {}).items():
            md.append(f"| {cat} | {cnt} |")

        # Guardrail Filter Details
        rejections = data.get("guardrail_rejections", [])
        if rejections:
            md.append("\n## Guardrail Filtering Details\n")
            md.append("| Article Title | Triggered Flags | Reason |")
            md.append("|---|---|---|")
            for rej in rejections:
                flags = ", ".join(rej.get("guardrail_flags", []))
                reason = rej.get("guardrail_reason", "")
                title = rej.get("title", "")[:45]
                md.append(f"| {title}... | `{flags}` | {reason} |")
        else:
            md.append("\n## Guardrail Filtering\n- Zero articles flagged for safety or gossip issues.")

        # Category Validation Details
        cat_val = data.get("category_validation", {})
        reassignments = cat_val.get("reassignments", [])
        if reassignments:
            md.append("\n## Category Cross-Validation Reassignments\n")
            md.append("| Article Title | From | Reassigned To | Confidence |")
            md.append("|---|---|---|---|")
            for item in reassignments:
                title = item.get("title", "")[:40]
                md.append(f"| {title}... | {item.get('from')} | **{item.get('to')}** | {item.get('confidence', 0):.2f} |")

        md.append("\n---\n*Report auto-generated by Todards Enterprise Pipeline.*")
        return "\n".join(md)
